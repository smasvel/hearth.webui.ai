"""Custom (user-authored) quiz decks + the merged deck registry + AI-generation helpers.

Built-in decks live in code (quiz_content.py); user-created decks live in PostgreSQL here.
list_decks() merges the two so the chat engine and the builder UI see one registry. Custom
decks are per-user (scoped by user_id); built-in decks are global.

Also holds the prompt-building and response-parsing for AI-generated quizzes — the actual
model call lives in app.py (it owns the backend clients), this module just shapes the
request and validates the result into the same question format everything else uses.
"""

from __future__ import annotations

import json
import re
import time
import uuid

import quiz_content
import database

SCHEMA = """
CREATE TABLE IF NOT EXISTS quiz_decks (
    slug TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    name TEXT NOT NULL,
    meta_json TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS quiz_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_slug TEXT NOT NULL REFERENCES quiz_decks(slug) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    q TEXT NOT NULL,
    options_json TEXT NOT NULL,
    answer INTEGER NOT NULL,
    explain TEXT
);
CREATE INDEX IF NOT EXISTS idx_quiz_questions_deck ON quiz_questions(deck_slug, position);
"""


def _connect():
    return database.connect()


def init_db() -> None:
    with _connect() as conn:
        conn.execute(SCHEMA)


# ---- registry ---------------------------------------------------------------------
def list_decks(user_id: str) -> list[dict]:
    """Built-in decks (global) + this user's custom decks, as picker rows."""
    rows = quiz_content.list_builtin()
    with _connect() as conn:
        for d in conn.execute(
            "SELECT slug, name, meta_json, "
            "(SELECT COUNT(*) FROM quiz_questions WHERE deck_slug = quiz_decks.slug) AS count "
            "FROM quiz_decks WHERE user_id = %s ORDER BY updated_at DESC",
            (user_id,),
        ).fetchall():
            meta = json.loads(d["meta_json"])
            rows.append({
                "slug": d["slug"], "name": d["name"], "category": "custom",
                "aliases": [d["name"].lower()], "meta": meta, "count": d["count"],
                "custom": True,
            })
    return rows


def get_bank(slug: str, user_id: str) -> dict | None:
    """Full bank (questions with stable ids) for a built-in OR this user's custom deck."""
    builtin = quiz_content.get_builtin(slug)
    if builtin:
        return builtin
    with _connect() as conn:
        deck = conn.execute(
            "SELECT slug, name, meta_json FROM quiz_decks WHERE slug = %s AND user_id = %s",
            (slug, user_id),
        ).fetchone()
        if not deck:
            return None
        qrows = conn.execute(
            "SELECT q, options_json, answer, explain FROM quiz_questions "
            "WHERE deck_slug = %s ORDER BY position ASC",
            (slug,),
        ).fetchall()
    questions = [
        {"id": i, "q": r["q"], "options": json.loads(r["options_json"]),
         "answer": r["answer"], "explain": r["explain"] or ""}
        for i, r in enumerate(qrows)
    ]
    return {
        "slug": deck["slug"], "name": deck["name"], "category": "custom",
        "meta": json.loads(deck["meta_json"]), "questions": questions,
    }


# ---- creating / deleting custom decks ---------------------------------------------
def _sanitize_questions(raw: list) -> list[dict]:
    """Keep only well-formed questions: a prompt, 2–6 options, a valid answer index."""
    clean = []
    for item in raw or []:
        if not isinstance(item, dict):
            continue
        q = (item.get("q") or item.get("question") or "").strip()
        options = item.get("options") or item.get("choices")
        if not q or not isinstance(options, list):
            continue
        options = [str(o).strip() for o in options if str(o).strip()]
        if not (2 <= len(options) <= 6):
            continue
        try:
            answer = int(item.get("answer"))
        except (TypeError, ValueError):
            continue
        if not (0 <= answer < len(options)):
            continue
        clean.append({
            "q": q, "options": options, "answer": answer,
            "explain": (item.get("explain") or item.get("explanation") or "").strip(),
        })
    return clean


def create_deck(user_id: str, name: str, questions: list, meta: dict | None = None) -> dict | None:
    """Create a custom deck. Returns its picker row, or None if no valid questions."""
    name = (name or "").strip()[:80] or "My quiz"
    clean = _sanitize_questions(questions)
    if not clean:
        return None
    slug = "custom-" + uuid.uuid4().hex[:10]
    now = time.time()
    meta = {
        "official_test_size": min((meta or {}).get("official_test_size", len(clean)), len(clean)),
        "pass_percent": (meta or {}).get("pass_percent", 70),
        "source": "Custom deck",
    }
    with _connect() as conn:
        conn.execute(
            "INSERT INTO quiz_decks (slug, user_id, name, meta_json, created_at, updated_at) "
            "VALUES (%s, %s, %s, %s, %s, %s)",
            (slug, user_id, name, json.dumps(meta), now, now),
        )
        for pos, q in enumerate(clean):
            conn.execute(
                "INSERT INTO quiz_questions (deck_slug, position, q, options_json, answer, explain) "
                "VALUES (%s, %s, %s, %s, %s, %s)",
                (slug, pos, q["q"], json.dumps(q["options"]), q["answer"], q["explain"]),
            )
    return {"slug": slug, "name": name, "category": "custom",
            "aliases": [name.lower()], "meta": meta, "count": len(clean), "custom": True}


def delete_deck(user_id: str, slug: str) -> bool:
    with _connect() as conn:
        owns = conn.execute(
            "SELECT 1 FROM quiz_decks WHERE slug = %s AND user_id = %s", (slug, user_id)
        ).fetchone()
        if not owns:
            return False
        conn.execute("DELETE FROM quiz_decks WHERE slug = %s AND user_id = %s", (slug, user_id))
    return True


# ---- AI generation (prompt + parse; the model call lives in app.py) ----------------
def build_generation_messages(topic: str, count: int) -> list[dict]:
    """Chat messages that ask a model to emit a strict JSON quiz. Kept deliberately
    forceful about the shape because small local models drift otherwise."""
    topic = (topic or "").strip()[:200]
    count = max(1, min(count, 20))
    system = (
        "You are a quiz generator. Output ONLY a valid JSON array — no prose, no markdown, "
        "no code fences. Each element is an object with exactly these keys: "
        '"q" (the question, a string), "options" (an array of exactly 4 distinct answer '
        'strings), "answer" (an integer 0-3 indexing the correct option), and "explain" '
        "(one short sentence explaining why the answer is correct). Make questions clear, "
        "factually correct, and unambiguous, with exactly one correct option."
    )
    user = (
        f"Generate {count} multiple-choice quiz questions about: {topic}. "
        f"Return a JSON array of {count} objects in the exact format described. "
        "Start your reply with [ and end with ]."
    )
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def parse_generated(text: str, count: int) -> list[dict]:
    """Pull the JSON array out of a model reply (tolerating code fences / stray prose) and
    validate it into our question format with stable ids. Returns [] if nothing parses."""
    if not text:
        return []
    raw = text.strip()
    # Strip ```json ... ``` fences if present.
    fence = re.search(r"```(?:json)?\s*(.+?)```", raw, re.DOTALL)
    if fence:
        raw = fence.group(1).strip()
    data = None
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        # Fall back to the first bracketed array in the text.
        start, end = raw.find("["), raw.rfind("]")
        if start != -1 and end != -1 and end > start:
            try:
                data = json.loads(raw[start:end + 1])
            except json.JSONDecodeError:
                data = None
    if isinstance(data, dict):  # a model might wrap it, e.g. {"questions": [...]}
        for key in ("questions", "quiz", "items", "data"):
            if isinstance(data.get(key), list):
                data = data[key]
                break
    if not isinstance(data, list):
        return []
    clean = _sanitize_questions(data)[:count]
    return [
        {"id": i, "q": q["q"], "options": q["options"], "answer": q["answer"],
         "explain": q["explain"]}
        for i, q in enumerate(clean)
    ]
