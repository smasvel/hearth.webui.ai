
-- Hearth-managed model registries, test reports, and reviewed resource metadata are
-- stored in PostgreSQL; backend model assets remain in their runtime-managed locations.
CREATE TABLE IF NOT EXISTS conversations (
    id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    model TEXT,
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    user_id TEXT
);
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    role TEXT NOT NULL,
    content TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    duration DOUBLE PRECISION,
    model TEXT,
    backend TEXT,
    prompt_tokens INTEGER,
    completion_tokens INTEGER,
    total_tokens INTEGER,
    reasoning TEXT,
    npu_percent DOUBLE PRECISION,
    tops_used DOUBLE PRECISION,
    tops_max DOUBLE PRECISION
);


CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user',
    created_at DOUBLE PRECISION NOT NULL,
    caddy_token TEXT,
    agentic_workflow_enabled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS auth_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
    username TEXT NOT NULL, event_type TEXT NOT NULL, succeeded BOOLEAN NOT NULL,
    remote_addr TEXT, actor_username TEXT, created_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_auth_events_created ON auth_events(created_at DESC);

CREATE TABLE IF NOT EXISTS app_secrets (
    name TEXT PRIMARY KEY,
    encrypted_value TEXT NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL
);
COMMENT ON TABLE app_secrets IS
    'Versioned authenticated ciphertext for application secrets such as the Flask session key.';

CREATE INDEX IF NOT EXISTS idx_users_agent_share_search
    ON users (lower(username) text_pattern_ops)
    WHERE agentic_workflow_enabled = TRUE;

CREATE TABLE IF NOT EXISTS agent_tasks (
    id TEXT PRIMARY KEY,
    owner_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    payload TEXT NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL
);
COMMENT ON COLUMN agent_tasks.payload IS
    'Serialized task state including started marker, cycle counters, saved responses, and completion data.';
CREATE INDEX IF NOT EXISTS idx_agent_tasks_owner ON agent_tasks(owner_id);
CREATE TABLE IF NOT EXISTS agent_workspace_files (
    owner_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    workspace_id TEXT NOT NULL DEFAULT '',
    path TEXT NOT NULL,
    content BYTEA NOT NULL DEFAULT ''::bytea,
    is_dir BOOLEAN NOT NULL DEFAULT FALSE,
    executable BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (owner_id, workspace_id, path)
);
CREATE TABLE IF NOT EXISTS agent_workspace_checkpoints (
    owner_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    workspace_id TEXT NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (owner_id, workspace_id)
);
CREATE TABLE IF NOT EXISTS agent_runtime_metadata (
    task_id TEXT PRIMARY KEY REFERENCES agent_tasks(id) ON DELETE CASCADE,
    container_name TEXT UNIQUE,
    payload TEXT NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS agent_schedules (
    id TEXT PRIMARY KEY,
    owner_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    payload TEXT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    next_run_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_agent_schedules_due ON agent_schedules(enabled, next_run_at);


CREATE TABLE IF NOT EXISTS memory_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    conversation_id TEXT NOT NULL,
    role TEXT NOT NULL,
    content TEXT NOT NULL,
    embedding BYTEA NOT NULL,
    created_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_memory_chunks_user ON memory_chunks(user_id);


CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS model_registry (
    backend TEXT NOT NULL,
    model_id TEXT NOT NULL,
    payload TEXT NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (backend, model_id)
);
COMMENT ON TABLE model_registry IS
    'Hearth-managed downloaded-model registry metadata, keyed by backend and model ID.';
COMMENT ON COLUMN model_registry.payload IS
    'Backend-specific model metadata such as local model path, context length, or dtype.';
CREATE TABLE IF NOT EXISTS model_test_runs (
    id TEXT PRIMARY KEY,
    started_at DOUBLE PRECISION NOT NULL,
    payload TEXT NOT NULL
);
COMMENT ON TABLE model_test_runs IS
    'Persisted model evaluation reports and active run state; downloadable reports are serialized from this table.';
CREATE INDEX IF NOT EXISTS idx_model_test_runs_started ON model_test_runs(started_at DESC);
CREATE TABLE IF NOT EXISTS model_resource_warnings (
    backend TEXT NOT NULL,
    model_id TEXT NOT NULL,
    reviewed_at TEXT NOT NULL,
    scope TEXT NOT NULL,
    payload TEXT NOT NULL,
    PRIMARY KEY (backend, model_id)
);
COMMENT ON TABLE model_resource_warnings IS
    'Reviewed model and backend resource observations used to annotate the model inventory.';
CREATE TABLE IF NOT EXISTS model_load_successes (
    backend TEXT NOT NULL,
    model_id TEXT NOT NULL,
    loaded_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (backend, model_id)
);
COMMENT ON TABLE model_load_successes IS
    'Successful Hearth model loads used to dismiss reviewed model warnings until another load fails.';
CREATE TABLE IF NOT EXISTS model_metadata_migrations (
    key TEXT PRIMARY KEY,
    migrated_at DOUBLE PRECISION NOT NULL
);
COMMENT ON TABLE model_metadata_migrations IS
    'One-time import markers for legacy model metadata files.';
COMMENT ON TABLE settings IS
    'Admin settings, backend credentials, and per-model compatibility profiles; provider API-key values are stored as versioned authenticated ciphertext.';


CREATE TABLE IF NOT EXISTS browse_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visited_at DOUBLE PRECISION NOT NULL,
    url TEXT NOT NULL,
    title TEXT,
    query TEXT,
    source TEXT,
    ok INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS idx_browse_history_visited_at
    ON browse_history(visited_at DESC);


CREATE TABLE IF NOT EXISTS quiz_decks (
    slug TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    name TEXT NOT NULL,
    meta_json TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS quiz_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_slug TEXT NOT NULL REFERENCES quiz_decks(slug) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    q TEXT NOT NULL,
    options_json TEXT NOT NULL,
    answer INTEGER NOT NULL,
    explain TEXT
);
CREATE INDEX IF NOT EXISTS idx_quiz_questions_deck ON quiz_questions(deck_slug, position);


CREATE TABLE IF NOT EXISTS request_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts DOUBLE PRECISION NOT NULL,
    source TEXT NOT NULL,          -- webui-chat | opencode | vscode | lan | image | ...
    backend TEXT,                  -- lmstudio | lemonade | vllm | kobold | fastflowlm | comfyui
    model TEXT,
    request_type TEXT,             -- chat_completion | completion | models | embeddings | image | ...
    ask_category TEXT,             -- chat | code | image | web-search | other
    duration_ms DOUBLE PRECISION,
    prompt_tokens INTEGER,
    completion_tokens INTEGER,
    total_tokens INTEGER,
    tokens_per_sec DOUBLE PRECISION,
    tops_used DOUBLE PRECISION,
    npu_percent DOUBLE PRECISION,
    status INTEGER,                -- HTTP status (200, 4xx, 5xx) or NULL
    client_ip TEXT,
    user_id TEXT,
    is_npu INTEGER,
    coding_passed INTEGER
);
CREATE INDEX IF NOT EXISTS idx_metrics_ts ON request_metrics(ts DESC);
CREATE INDEX IF NOT EXISTS idx_metrics_source ON request_metrics(source);

CREATE TABLE IF NOT EXISTS developer_traces (id BIGINT PRIMARY KEY, finished_at DOUBLE PRECISION NOT NULL, payload TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS idx_developer_traces_finished ON developer_traces(finished_at);
