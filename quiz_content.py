def list_builtin() -> list[dict]:
    """Registry rows for the deck picker — no question bodies, just metadata + count."""
    return [
        {
            "slug": d["slug"], "name": d["name"], "category": d["category"],
            "aliases": d["aliases"], "meta": d["meta"], "count": len(d["questions"]),
            "custom": False,
        }
        for d in BUILTIN_DECKS
    ]


def get_builtin(slug: str) -> dict | None:
    """Full bank for one built-in deck, each question with a stable integer id (its index),
    matching the shape quiz_store returns for custom decks."""
    d = _BY_SLUG.get((slug or "").lower())
    if not d:
        return None
    questions = [
        {"id": i, "q": q["q"], "options": q["options"], "answer": q["answer"], "explain": q["explain"]}
        for i, q in enumerate(d["questions"])
    ]
    return {
        "slug": d["slug"], "name": d["name"], "category": d["category"],
        "meta": d["meta"], "questions": questions,
    }
