"""Cross-conversation memory: embeds each message and lets later conversations retrieve
relevant snippets from a user's *other* past chats via cosine similarity.

Shares chat_store's PostgreSQL database rather than a separate database — same per-user scoping,
same lifecycle (deleting a user/conversation should take its memory with it).
"""

from __future__ import annotations

import database
import time
import re

import numpy as np


SCHEMA = """
CREATE TABLE IF NOT EXISTS memory_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    conversation_id TEXT NOT NULL,
    role TEXT NOT NULL,
    content TEXT NOT NULL,
    embedding BYTEA NOT NULL,
    created_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_memory_chunks_user ON memory_chunks(user_id);
"""


def _connect():
    return database.connect()


def init_db() -> None:
    with _connect() as conn:
        conn.execute(SCHEMA)


def delete_conversation_chunks(conversation_id: str) -> None:
    with _connect() as conn:
        conn.execute("DELETE FROM memory_chunks WHERE conversation_id = %s", (conversation_id,))


def delete_user_chunks(user_id: str) -> None:
    with _connect() as conn:
        conn.execute("DELETE FROM memory_chunks WHERE user_id = %s", (user_id,))


def all_chunks() -> list[dict]:
    """Every stored chunk's id + content, for re-embedding after switching embedding
    models (vectors from different models live in incompatible spaces, so swapping the
    embedding backend requires replacing every stored vector, not just new ones going
    forward)."""
    with _connect() as conn:
        rows = conn.execute("SELECT id, content FROM memory_chunks").fetchall()
    return [{"id": r["id"], "content": r["content"]} for r in rows]


def update_chunk_embedding(chunk_id: int, embedding: list[float]) -> None:
    vector = np.asarray(embedding, dtype=np.float32).tobytes()
    with _connect() as conn:
        conn.execute("UPDATE memory_chunks SET embedding = %s WHERE id = %s", (vector, chunk_id))


def find_near_duplicate(user_id: str, role: str, embedding: list[float], threshold: float = 0.9) -> bool:
    """Check for near-duplicate chunks with the same user and role.

    Repeated questions can crowd relevant facts out of the retrieval window.
    Compare only chunks with the same role to preserve question-answer pairs."""
    with _connect() as conn:
        rows = conn.execute(
            "SELECT embedding FROM memory_chunks WHERE user_id = %s AND role = %s",
            (user_id, role),
        ).fetchall()
    if not rows:
        return False
    query = np.asarray(embedding, dtype=np.float32)
    query_norm = np.linalg.norm(query)
    if query_norm == 0:
        return False
    vectors = [
        vector for r in rows
        if (vector := _decode_compatible_vector(r["embedding"], query.size)) is not None
    ]
    if not vectors:
        return False
    vectors = np.stack(vectors)
    norms = np.linalg.norm(vectors, axis=1)
    norms[norms == 0] = 1e-9
    similarities = (vectors @ query) / (norms * query_norm)
    return bool(np.max(similarities) >= threshold)


def add_chunk(user_id: str, conversation_id: str, role: str, content: str, embedding: list[float]) -> None:
    vector = np.asarray(embedding, dtype=np.float32).tobytes()
    with _connect() as conn:
        conn.execute(
            "INSERT INTO memory_chunks (user_id, conversation_id, role, content, embedding, created_at) "
            "VALUES (%s, %s, %s, %s, %s, %s)",
            (user_id, conversation_id, role, content, vector, time.time()),
        )


def _decode_compatible_vector(blob: bytes, expected_size: int) -> np.ndarray | None:
    """Decode one stored vector, ignoring stale/corrupt embedding rows.

    A changed embedding model can leave old dimensions in the database if a
    re-index is interrupted. One such row must not make np.stack() abort recall
    for every otherwise-valid memory belonging to the user.
    """
    try:
        vector = np.frombuffer(blob, dtype=np.float32)
    except (TypeError, ValueError):
        return None
    if vector.size != expected_size or not np.all(np.isfinite(vector)):
        return None
    return vector


_LOCATION_PATTERNS = (
    re.compile(r"\bset\s+my\s+(?:current\s+)?location\s+(?:as|to)\s+(.+)", re.I),
    re.compile(r"\bmy\s+(?:current\s+)?(?:city|location)\s+is\s+(.+)", re.I),
    re.compile(r"\bi\s+(?:live|reside)\s+in\s+(.+)", re.I),
)


def latest_location(user_id: str, exclude_conversation_id: str | None = None) -> dict | None:
    """Return the newest explicit user-stated home/current location.

    Personal facts are too important to leave entirely to embedding rank: generic
    weather refusals frequently score above an imperative such as "set my current
    location as Exampleville ZZ". Keep the source message so recall remains auditable.
    Store-specific addresses ("remember my Great Clips location") intentionally do
    not match these personal-location patterns.
    """
    with _connect() as conn:
        rows = conn.execute(
            "SELECT conversation_id, content, created_at FROM memory_chunks "
            "WHERE user_id = %s AND role = 'user' ORDER BY created_at DESC, id DESC",
            (user_id,),
        ).fetchall()
    for row in rows:
        if row["conversation_id"] == exclude_conversation_id:
            continue
        text = (row["content"] or "").strip()
        for pattern in _LOCATION_PATTERNS:
            match = pattern.search(text)
            if match:
                value = match.group(1).strip().rstrip(".!? ")[:200]
                if value:
                    return {
                        "location": value,
                        "content": text,
                        "conversation_id": row["conversation_id"],
                        "created_at": row["created_at"],
                    }
    return None


def search(
    user_id: str,
    query_embedding: list[float],
    exclude_conversation_id: str | None = None,
    top_k: int = 8,
    min_similarity: float = 0.35,
) -> list[dict]:
    """Search stored chunks by cosine similarity, scoped to the current user.

    Exclude the current conversation. A minimum similarity of 0.35 and a retrieval
    window of eight help retrieve short facts despite repeated similar questions."""
    with _connect() as conn:
        rows = conn.execute(
            "SELECT conversation_id, role, content, embedding, created_at FROM memory_chunks "
            "WHERE user_id = %s",
            (user_id,),
        ).fetchall()

    candidates = [r for r in rows if r["conversation_id"] != exclude_conversation_id]
    if not candidates:
        return []

    query = np.asarray(query_embedding, dtype=np.float32)
    query_norm = np.linalg.norm(query)
    if query_norm == 0:
        return []

    compatible = [
        (row, vector)
        for row in candidates
        if (vector := _decode_compatible_vector(row["embedding"], query.size)) is not None
    ]
    if not compatible:
        return []
    candidates = [row for row, _ in compatible]
    vectors = np.stack([vector for _, vector in compatible])
    norms = np.linalg.norm(vectors, axis=1)
    norms[norms == 0] = 1e-9
    similarities = (vectors @ query) / (norms * query_norm)

    ranked = sorted(zip(similarities, candidates), key=lambda p: p[0], reverse=True)
    results = []
    for similarity, row in ranked[:top_k]:
        if similarity < min_similarity:
            break
        results.append(
            {
                "conversation_id": row["conversation_id"],
                "role": row["role"],
                "content": row["content"],
                "created_at": row["created_at"],
                "similarity": float(similarity),
            }
        )
    return results
