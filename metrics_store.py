"""PostgreSQL-backed capture of per-request performance metrics, for the admin metric board.

Every inference request is recorded as one row: where it came from (webui chat, OpenCode,
VSCode/Continue, or another LAN client), which backend/model served it, what kind of request
and "ask" it was, how long it took, tokens in/out, and NPU TOPS where known.

Two feeders:
  * webui chat  — app.py records a full row after each /api/chat turn (exact tokens + TOPS).
  * LAN tools   — a background tailer of Caddy's JSON access log records OpenCode/VSCode hits
                  (response time, request type, source, backend, status, bytes). Token/TOPS
                  aren't visible at the proxy layer, so those stay NULL for LAN rows.
"""

from __future__ import annotations

import database
import time

DATA_DIR = database.DATA_DIR

SCHEMA = """
CREATE TABLE IF NOT EXISTS request_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts DOUBLE PRECISION NOT NULL,
    source TEXT NOT NULL,          -- webui-chat | opencode | vscode | lan | image | ...
    backend TEXT,                  -- lmstudio | lemonade | vllm | kobold | fastflowlm | comfyui
    model TEXT,
    request_type TEXT,             -- chat_completion | completion | models | embeddings | image | ...
    ask_category TEXT,             -- chat | code | image | web-search | other
    duration_ms DOUBLE PRECISION,
    prompt_tokens INTEGER,
    completion_tokens INTEGER,
    total_tokens INTEGER,
    tokens_per_sec DOUBLE PRECISION,
    tops_used DOUBLE PRECISION,
    npu_percent DOUBLE PRECISION,
    status INTEGER,                -- HTTP status (200, 4xx, 5xx) or NULL
    client_ip TEXT,
    user_id TEXT
);
CREATE INDEX IF NOT EXISTS idx_metrics_ts ON request_metrics(ts DESC);
CREATE INDEX IF NOT EXISTS idx_metrics_source ON request_metrics(source);
"""

# Added after the table already existed in the wild (2026-07-26) — same ALTER-TABLE-in-a-
# idempotent ADD COLUMN migrations used for post-launch columns.
# is_npu: 1 = confirmed served by the actual NPU (fastflowlm backend, or a Lemonade model
# whose catalog `recipe` is "flm" — see lemonade_client.is_npu_model()'s docstring for why
# this can't be guessed from the model's name), 0 = confirmed not, NULL = unknown. LAN rows
# recorded by caddy_metrics.py never see the request body (no model id at all), so a Lemonade
# LAN/OpenCode row stays NULL here rather than a guessed 0 or 1 — only webui-chat rows (this
# app's own process, full body access) and FastFlowLM LAN rows (fastflowlm is NPU-only
# regardless of model, so no body access is even needed) can be answered with confidence.
_MIGRATION_COLUMNS = [("is_npu", "INTEGER"), ("coding_passed", "INTEGER")]


def _connect():
    return database.connect()


def init_db() -> None:
    with _connect() as conn:
        conn.execute(SCHEMA)
        for column, sql_type in _MIGRATION_COLUMNS:
            conn.execute(f"ALTER TABLE request_metrics ADD COLUMN IF NOT EXISTS {column} {sql_type}")


def record(**fields) -> None:
    """Insert one metrics row. Fail-soft — metrics must never break a request. Unknown keys
    are ignored; ts defaults to now."""
    cols = ("ts", "source", "backend", "model", "request_type", "ask_category", "duration_ms",
            "prompt_tokens", "completion_tokens", "total_tokens", "tokens_per_sec", "tops_used",
            "npu_percent", "status", "client_ip", "user_id", "is_npu")
    row = {c: fields.get(c) for c in cols}
    if not row["ts"]:
        row["ts"] = time.time()
    if not row.get("source"):
        return
    if row["is_npu"] is not None:
        row["is_npu"] = int(bool(row["is_npu"]))
    try:
        with _connect() as conn:
            conn.execute(
                f"INSERT INTO request_metrics ({','.join(cols)}) VALUES ({','.join(['%s'] * len(cols))})",
                [row[c] for c in cols],
            )
    except database.Error:
        pass  # never propagate a metrics failure into the request path


def _window_clause(hours: float | None) -> tuple[str, list]:
    if not hours:
        return "", []
    return " WHERE ts >= %s", [time.time() - hours * 3600]


def summary(hours: float | None = 24) -> dict:
    """Aggregates for the dashboard: KPI totals, breakdowns by source/backend/type, a
    time-series of request counts, and latency stats. The recent-requests table is served
    separately by recent() below (paginated/filterable, so it doesn't need this whole
    aggregate payload re-fetched just to turn a page or change a filter)."""
    where, params = _window_clause(hours)
    with _connect() as conn:
        c = conn.cursor()

        totals = c.execute(
            f"SELECT COUNT(*) n, "
            f"       COALESCE(SUM(total_tokens),0) tokens, "
            f"       COALESCE(SUM(completion_tokens),0) out_tokens, "
            f"       AVG(duration_ms) avg_ms, "
            f"       AVG(tokens_per_sec) avg_tps, "
            f"       AVG(NULLIF(tops_used,0)) avg_tops, "
            f"       SUM(CASE WHEN is_npu = 1 THEN 1 ELSE 0 END) npu_n, "
            f"       SUM(CASE WHEN is_npu IS NOT NULL THEN 1 ELSE 0 END) npu_known_n "
            f"FROM request_metrics{where}", params).fetchone()

        def group(col):
            return [dict(r) for r in c.execute(
                f"SELECT COALESCE({col},'?') k, COUNT(*) n, "
                f"       COALESCE(SUM(total_tokens),0) tokens, AVG(duration_ms) avg_ms "
                f"FROM request_metrics{where} GROUP BY {col} ORDER BY n DESC", params).fetchall()]

        # Run all grouped queries while the connection is still open.
        by_source = group("source")
        by_backend = group("backend")
        by_type = group("ask_category")
        by_model = model_report(hours, conn)

        # p95 latency (approx: order + offset)
        lat = [r[0] for r in c.execute(
            f"SELECT duration_ms FROM request_metrics{where}"
            f"{' AND' if where else ' WHERE'} duration_ms IS NOT NULL ORDER BY duration_ms",
            params).fetchall()]
        p95 = lat[int(len(lat) * 0.95)] if lat else None

        # time series: requests per hour bucket over the window
        bucket = 3600
        series = [dict(r) for r in c.execute(
            f"SELECT FLOOR(ts/{bucket})::BIGINT*{bucket} bucket, COUNT(*) n, "
            f"       COALESCE(SUM(total_tokens),0) tokens "
            f"FROM request_metrics{where} GROUP BY bucket ORDER BY bucket", params).fetchall()]

    return {
        "window_hours": hours,
        "totals": {
            "requests": totals["n"] or 0,
            "total_tokens": totals["tokens"] or 0,
            "output_tokens": totals["out_tokens"] or 0,
            "avg_ms": round(totals["avg_ms"], 1) if totals["avg_ms"] else None,
            "p95_ms": round(p95, 1) if p95 else None,
            "avg_tps": round(totals["avg_tps"], 1) if totals["avg_tps"] else None,
            "avg_tops": round(totals["avg_tops"], 1) if totals["avg_tops"] else None,
            "npu_requests": totals["npu_n"] or 0,
            # Percentage of requests *with a known answer* that were NPU-served — denominator
            # is npu_known_n, not the full n, because Lemonade-via-LAN rows (caddy_metrics.py,
            # no request-body access) always record is_npu as NULL/unknown rather than a
            # guessed 0; counting those against n would understate NPU usage instead of just
            # reporting "unknown" for the slice that genuinely is.
            "pct_npu": round(totals["npu_n"] / totals["npu_known_n"] * 100, 1) if totals["npu_known_n"] else None,
        },
        "by_source": by_source,
        "by_backend": by_backend,
        "by_type": by_type,
        "by_model": by_model,
        "series": series,
    }


def model_report(hours: float | None = 24, conn=None) -> list[dict]:
    """Compare generation requests only; correctness comes from explicit reviews."""
    if conn is None:
        with _connect() as connection:
            return model_report(hours, connection)
    where, params = _window_clause(hours)
    where += (" AND" if where else " WHERE") + " request_type IN ('chat_completion','completion')"
    rows = [dict(r) for r in conn.execute(f"""
        SELECT COALESCE(NULLIF(model,''),'Unknown model') model,
               COALESCE(backend,'Unknown backend') backend, COUNT(*) requests,
               SUM(prompt_tokens) input_tokens, SUM(completion_tokens) output_tokens,
               COUNT(completion_tokens) token_samples,
               AVG(tokens_per_sec) avg_tps, COUNT(tokens_per_sec) speed_samples,
               AVG(duration_ms) avg_ms,
               SUM(CASE WHEN status >= 200 AND status < 400 THEN 1 ELSE 0 END) succeeded,
               SUM(CASE WHEN status >= 400 AND status < 500 THEN 1 ELSE 0 END) client_errors,
               SUM(CASE WHEN status >= 500 THEN 1 ELSE 0 END) server_errors,
               SUM(CASE WHEN status IS NULL OR status < 200 THEN 1 ELSE 0 END) unknown_status,
               SUM(CASE WHEN ask_category='code' THEN 1 ELSE 0 END) coding_requests,
               SUM(CASE WHEN ask_category='code' AND status >= 400 THEN 1 ELSE 0 END) coding_errors,
               SUM(CASE WHEN ask_category='code' AND coding_passed IS NOT NULL THEN 1 ELSE 0 END) reviewed,
               SUM(CASE WHEN ask_category='code' AND coding_passed=1 THEN 1 ELSE 0 END) coding_passes
        FROM request_metrics{where}
        GROUP BY 1,2 ORDER BY requests DESC, model, backend
    """, params)]
    for row in rows:
        known = row['succeeded'] + row['client_errors'] + row['server_errors']
        row['error_rate'] = round((row['client_errors'] + row['server_errors']) / known * 100, 1) if known else None
        row['coding_accuracy'] = round(row['coding_passes'] / row['reviewed'] * 100, 1) if row['reviewed'] else None
    return rows


def review_coding(request_id: int, passed: bool | None) -> bool:
    with _connect() as conn:
        return conn.execute(
            "UPDATE request_metrics SET coding_passed=%s WHERE id=%s AND ask_category='code' "
            "AND request_type IN ('chat_completion','completion')",
            (None if passed is None else int(passed), request_id),
        ).rowcount == 1


_STATUS_CLASS_SQL = {
    "ok": "status < 400",
    "warn": "status >= 400 AND status < 500",
    "err": "status >= 500",
}


def recent(
    hours: float | None = 24,
    page: int = 1,
    page_size: int = 50,
    source: str | None = None,
    backend: str | None = None,
    request_type: str | None = None,
    ask_category: str | None = None,
    status_class: str | None = None,
    model: str | None = None,
    sort: str = "id",
    direction: str = "desc",
) -> dict:
    """Paginated, filterable request log for the Recent Requests table — split out from
    summary() above (which stays focused on the KPI/bars/series aggregates) so changing a
    table filter or page doesn't require re-fetching/re-rendering the whole dashboard.

    Real gap this replaces: the table used to be an unconditional `ORDER BY id DESC LIMIT 60`
    with no relation to the page's own hours selector at all — switching the range dropdown to
    "Last hour" changed every KPI/chart except the table sitting right below them, and there
    was no way to see anything past the newest 60 rows or narrow down to one backend/model/
    status while investigating something. `status_class` buckets into ok/warn/err (matching the
    table's own existing color-coding) rather than exact HTTP codes, which is what's actually
    useful to filter by; `model` is a substring match, since exact model ids are long and
    easy to mistype."""
    where_sql, params = _window_clause(hours)
    conj = "WHERE" if not where_sql else "AND"

    def add(col: str, val, op: str = "="):
        nonlocal where_sql, conj
        if val:
            where_sql += f" {conj} {col} {op} %s"
            params.append(val)
            conj = "AND"

    add("source", source)
    add("backend", backend)
    add("request_type", request_type)
    add("ask_category", ask_category)
    if model:
        add("model", f"%{model}%", "ILIKE")
    if status_class in _STATUS_CLASS_SQL:
        where_sql += f" {conj} {_STATUS_CLASS_SQL[status_class]}"
        conj = "AND"

    page = max(1, page)
    page_size = max(1, min(page_size, 200))
    offset = (page - 1) * page_size
    sortable = {"id", "ts", "source", "backend", "model", "request_type", "ask_category",
                "duration_ms", "prompt_tokens", "completion_tokens", "total_tokens",
                "tokens_per_sec", "tops_used", "npu_percent", "is_npu", "status",
                "client_ip", "user_id", "coding_passed"}
    sort = sort if sort in sortable else "id"
    order = "ASC" if direction == "asc" else "DESC"
    text_columns = {"source", "backend", "model", "request_type", "ask_category", "client_ip", "user_id"}
    sort_expression = f"LOWER({sort})" if sort in text_columns else sort

    with _connect() as conn:
        c = conn.cursor()
        total = c.execute(f"SELECT COUNT(*) FROM request_metrics{where_sql}", params).fetchone()[0]
        rows = [dict(r) for r in c.execute(
            "SELECT id, ts, source, backend, model, request_type, ask_category, duration_ms, "
            "prompt_tokens, completion_tokens, total_tokens, tokens_per_sec, tops_used, "
            "npu_percent, is_npu, status, client_ip, user_id, coding_passed "
            f"FROM request_metrics{where_sql} ORDER BY {sort} IS NULL, {sort_expression} {order}, id DESC LIMIT %s OFFSET %s",
            [*params, page_size, offset]).fetchall()]
        # Distinct values actually present in this window, for the filter dropdowns — narrower
        # and more accurate than a hardcoded list (e.g. no "kobold" option shown if nothing has
        # hit it yet in the selected range).
        def distinct(col):
            win_sql, win_params = _window_clause(hours)
            win_conj = "AND" if win_sql else "WHERE"
            return [r[0] for r in c.execute(
                f"SELECT DISTINCT {col} FROM request_metrics{win_sql} "
                f"{win_conj} {col} IS NOT NULL ORDER BY {col}", win_params).fetchall()]
        filters = {
            "sources": distinct("source"),
            "backends": distinct("backend"),
            "request_types": distinct("request_type"),
            "ask_categories": distinct("ask_category"),
        }

    return {
        "rows": rows,
        "total": total,
        "page": page,
        "page_size": page_size,
        "total_pages": max(1, -(-total // page_size)),
        "filters": filters,
    }
