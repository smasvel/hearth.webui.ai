"""PostgreSQL-backed history of every page the AI's browser actually visits.

Fed by page_scraper.fetch_pages() — the single choke point every real Playwright
page visit goes through (searches, explicit browse requests, pasted URLs,
shopping-price scrapes all funnel there), so recording here catches everything
without each caller needing to remember to log. Failures are recorded too
(ok=0): "the AI tried this link and it didn't load" is real history, and its
absence would make the history page silently lie about what was attempted.

Uses the shared PostgreSQL database with a short-lived transaction per call.
"""

from __future__ import annotations

import database
import time

DATA_DIR = database.DATA_DIR

SCHEMA = """
CREATE TABLE IF NOT EXISTS browse_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visited_at DOUBLE PRECISION NOT NULL,
    url TEXT NOT NULL,
    title TEXT,
    query TEXT,
    source TEXT,
    ok INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS idx_browse_history_visited_at
    ON browse_history(visited_at DESC);
"""


def _connect():
    return database.connect()


def init_db() -> None:
    with _connect() as conn:
        conn.execute(SCHEMA)


def add_visit(url: str, title: str | None, query: str | None, source: str | None, ok: bool) -> None:
    """One row per actual page visit. Never raises — history recording must not be able
    to break the browse it's recording (same fail-soft contract as the rest of the
    web-search plumbing)."""
    try:
        with _connect() as conn:
            conn.execute(
                "INSERT INTO browse_history (visited_at, url, title, query, source, ok) "
                "VALUES (%s, %s, %s, %s, %s, %s)",
                (time.time(), url, title or None, query or None, source or None, 1 if ok else 0),
            )
    except database.Error:
        pass


def list_history(search: str | None = None, page: int = 1, per_page: int = 25) -> dict:
    """Newest-first page of history rows plus the total match count (for pagination).
    `search` does a case-insensitive substring match across url, title, and the query
    that led there — one box searching all three is what "live history search" needs;
    nobody remembers which field the thing they're looking for appeared in."""
    page = max(1, page)
    per_page = max(1, min(per_page, 200))
    where = ""
    params: list = []
    if search and search.strip():
        like = f"%{search.strip()}%"
        where = "WHERE url ILIKE %s OR title ILIKE %s OR query ILIKE %s"
        params = [like, like, like]
    with _connect() as conn:
        total = conn.execute(
            f"SELECT COUNT(*) FROM browse_history {where}", params
        ).fetchone()[0]
        rows = conn.execute(
            f"SELECT id, visited_at, url, title, query, source, ok FROM browse_history "
            f"{where} ORDER BY visited_at DESC, id DESC LIMIT %s OFFSET %s",
            params + [per_page, (page - 1) * per_page],
        ).fetchall()
    return {
        "total": total,
        "page": page,
        "per_page": per_page,
        "entries": [dict(r) for r in rows],
    }


def delete_visit(visit_id: int) -> bool:
    with _connect() as conn:
        row = conn.execute("DELETE FROM browse_history WHERE id = %s RETURNING id", (visit_id,)).fetchone()
    return row is not None


def clear_history() -> int:
    with _connect() as conn:
        rows = conn.execute("DELETE FROM browse_history RETURNING id").fetchall()
    return len(rows)
