"""Cross-conversation memory: embeds each message and lets later conversations retrieve
relevant snippets from a user's *other* past chats via cosine similarity.

Shares chat_store's PostgreSQL database rather than a separate database — same per-user scoping,
same lifecycle (deleting a user/conversation should take its memory with it).
"""

from __future__ import annotations

from hearth.storage import database
import time
import re

import numpy as np


SCHEMA = """
CREATE TABLE IF NOT EXISTS memory_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    conversation_id TEXT NOT NULL,
    role TEXT NOT NULL,
    content TEXT NOT NULL,
    embedding BYTEA NOT NULL,
    embedding_backend TEXT NOT NULL DEFAULT 'lemonade',
    created_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_memory_chunks_user ON memory_chunks(user_id);
"""


def _connect():
    return database.connect()


def init_db() -> None:
    with _connect() as conn:
        conn.execute(SCHEMA)
        conn.execute("ALTER TABLE memory_chunks ADD COLUMN IF NOT EXISTS embedding_backend TEXT NOT NULL DEFAULT 'lemonade'")


def delete_conversation_chunks(conversation_id: str) -> None:
    with _connect() as conn:
        conn.execute("DELETE FROM memory_chunks WHERE conversation_id = %s", (conversation_id,))


def delete_user_chunks(user_id: str) -> None:
    with _connect() as conn:
        conn.execute("DELETE FROM memory_chunks WHERE user_id = %s", (user_id,))


def all_chunks() -> list[dict]:
    """Every stored chunk's id + content, for re-embedding after switching embedding
    models (vectors from different models live in incompatible spaces, so swapping the
    embedding backend requires replacing every stored vector, not just new ones going
    forward)."""
    with _connect() as conn:
        rows = conn.execute("SELECT id, content FROM memory_chunks").fetchall()
    return [{"id": r["id"], "content": r["content"]} for r in rows]


def update_chunk_embedding(chunk_id: int, embedding: list[float]) -> None:
    vector = np.asarray(embedding, dtype=np.float32).tobytes()
    with _connect() as conn:
        conn.execute("UPDATE memory_chunks SET embedding = %s WHERE id = %s", (vector, chunk_id))


def find_near_duplicate(user_id: str, role: str, embedding: list[float], threshold: float = 0.9,
                        embedding_backend: str = "lemonade") -> bool:
    """Check for near-duplicate chunks with the same user and role.

    Repeated questions can crowd relevant facts out of the retrieval window.
    Compare only chunks with the same role to preserve question-answer pairs."""
    with _connect() as conn:
        rows = conn.execute(
            "SELECT embedding FROM memory_chunks WHERE user_id = %s AND role = %s AND embedding_backend = %s",
            (user_id, role, embedding_backend),
        ).fetchall()
    if not rows:
        return False
    query = np.asarray(embedding, dtype=np.float32)
    query_norm = np.linalg.norm(query)
    if query_norm == 0:
        return False
    vectors = [
        vector for r in rows
        if (vector := _decode_compatible_vector(r["embedding"], query.size)) is not None
    ]
    if not vectors:
        return False
    vectors = np.stack(vectors)
    norms = np.linalg.norm(vectors, axis=1)
    norms[norms == 0] = 1e-9
    similarities = (vectors @ query) / (norms * query_norm)
    return bool(np.max(similarities) >= threshold)


def has_exact_user_chunk(user_id: str, content: str, embedding_backend: str) -> bool:
    """Deduplicate repeated text without discarding a changed user fact."""
    with _connect() as conn:
        return conn.execute(
            "SELECT 1 FROM memory_chunks WHERE user_id = %s AND role = 'user' "
            "AND embedding_backend = %s AND content = %s LIMIT 1",
            (user_id, embedding_backend, content),
        ).fetchone() is not None


def has_user_embeddings(user_id: str, embedding_backend: str, exclude_conversation_id: str) -> bool:
    with _connect() as conn:
        return conn.execute(
            "SELECT 1 FROM memory_chunks WHERE user_id = %s AND embedding_backend = %s "
            "AND conversation_id <> %s AND role = 'user' LIMIT 1",
            (user_id, embedding_backend, exclude_conversation_id),
        ).fetchone() is not None


def add_chunk(user_id: str, conversation_id: str, role: str, content: str, embedding: list[float],
              embedding_backend: str = "lemonade") -> None:
    vector = np.asarray(embedding, dtype=np.float32).tobytes()
    with _connect() as conn:
        conn.execute(
            "INSERT INTO memory_chunks (user_id, conversation_id, role, content, embedding, embedding_backend, created_at) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s)",
            (user_id, conversation_id, role, content, vector, embedding_backend, time.time()),
        )


def _decode_compatible_vector(blob: bytes, expected_size: int) -> np.ndarray | None:
    """Decode one stored vector, ignoring stale/corrupt embedding rows.

    A changed embedding model can leave old dimensions in the database if a
    re-index is interrupted. One such row must not make np.stack() abort recall
    for every otherwise-valid memory belonging to the user.
    """
    try:
        vector = np.frombuffer(blob, dtype=np.float32)
    except (TypeError, ValueError):
        return None
    if vector.size != expected_size or not np.all(np.isfinite(vector)):
        return None
    return vector


_REMEMBER_LOCATION = re.compile(
    r"^(?:please\s+)?(?:remember|save|set|update|note|record|store)\s+my\s+(?:current\s+|home\s+)?"
    r"(?:city\s+and\s+state|city|location)\b"
    r"(?:\s+(?:as|to|is|are)\b)?[\s:,-]+(.+)",
    re.I,
)


_LOCATION_PATTERNS = (
    _REMEMBER_LOCATION,
    re.compile(r"\bmy\s+(?:current\s+)?(?:city|location)\s+is\s+(.+)", re.I),
    re.compile(r"\bmy\s+city\s+and\s+state\s+(?:are|is)\s+(.+)", re.I),
    re.compile(r"\bi\s+(?:live|reside)\s+in\s+(.+)", re.I),
    re.compile(r"\bi(?:'m| am)\s+(?:currently\s+)?(?:located|based|living)\s+in\s+(.+)", re.I),
)
_STATE_PATTERN = re.compile(r"\bmy\s+(?:home\s+)?state\s+is\s+(.+)", re.I)
_SAVED_LOCATION_PROMPT = re.compile(
    r"^(?:which|what) (?:city|location) (?:should i|would you like me to) (?:check|use|remember)\?"
    r"|^where do you live\?",
    re.I,
)


def requested_saved_location(text: str) -> str | None:
    """Extract the place from an explicit request to save a personal location."""
    text = text.strip()
    match = _REMEMBER_LOCATION.match(text)
    if not match or text.endswith("?"):
        return None
    value = re.sub(r"^(?:the\s+)?city(?:\s+of)?\s+", "", match[1].strip(), flags=re.I)
    value = value.rstrip(".! ")[:200]
    if not value or re.match(r"^(?:not|unknown|none|from|for|when|as|to|is|are|here|again)\b", value, re.I):
        return None
    return value


def _location_from_followup(user_id, exclude_conversation_id, newer_than):
    """Find a place supplied by the owner after an explicit chat location question."""
    with _connect() as conn:
        rows = conn.execute("""
            SELECT conversation_id, content, created_at, previous_text, previous_question FROM (
                SELECT m.conversation_id, m.content, m.created_at, m.role,
                    lag(m.role) OVER turns AS previous_role,
                    lag(m.content) OVER turns AS previous_text,
                    lag(m.content, 2) OVER turns AS previous_question
                FROM messages m JOIN conversations c ON c.id = m.conversation_id
                WHERE c.user_id = %s AND c.id IS DISTINCT FROM %s
                WINDOW turns AS (PARTITION BY m.conversation_id ORDER BY m.created_at, m.id)
            ) history
            WHERE role = 'user' AND previous_role = 'assistant' AND created_at > %s
              AND (previous_text ILIKE 'which city %%' OR previous_text ILIKE 'what city %%'
                   OR previous_text ILIKE 'which location %%' OR previous_text ILIKE 'what location %%'
                   OR previous_text ILIKE 'where do you live?%%')
            ORDER BY created_at DESC
        """, (user_id, exclude_conversation_id, newer_than)).fetchall()
    for row in rows:
        place = row["content"].strip().rstrip(".! ")
        prompt = row["previous_text"].strip()
        personal = re.search(r"\b(?:remember|where do you live)\b", prompt, re.I) or re.search(
            r"\b(?:my (?:current )?(?:city|location)|where i live)\b", row["previous_question"] or "", re.I,
        )
        # Bare city answers need a city and region, or a capitalized place name.
        # A chat model's guess can provide the question, never the saved value.
        if (personal and _SAVED_LOCATION_PROMPT.match(prompt)
                and re.fullmatch(r"[^\W\d_][\w .’'-]{1,60}(?:,\s*[^\W\d_][\w .’'-]{1,60}){0,2}", place)
                and ("," in place or place.istitle())
                and place.casefold() not in {"thanks", "okay", "sure", "nope", "not sure", "unknown", "here", "yes", "no"}):
            return {"conversation_id": row["conversation_id"], "content": row["content"],
                    "created_at": row["created_at"], "location": place, "is_state": False}
    return None


_NAME_PATTERNS = (
    re.compile(r"\bmy\s+name(?:'s|\s+is)\s+([A-Za-z][A-Za-z .'-]*)", re.I),
    re.compile(r"\bcall\s+me\s+([A-Za-z][A-Za-z .'-]*)", re.I),
)
_NAME_REJECT_VALUES = {
    "not", "unknown", "nothing", "none", "n/a", "same",
    # Non-name completions of "call me ..." that still match the letter pattern.
    "later", "back", "anytime", "maybe", "when", "if", "asap", "once",
    "today", "tomorrow",
}


def _recent_user_messages(user_id: str, limit: int | None = 2000) -> list[dict]:
    """Read explicit user text from both the searchable memory index and chat history.

    Chat history is the source of truth for saved facts. A memory chunk may be absent
    when the embedding service was offline at the time a turn was stored.
    """
    with _connect() as conn:
        return conn.execute(
            "SELECT conversation_id, content, created_at FROM ("
            "SELECT conversation_id, content, created_at, id FROM memory_chunks "
            "WHERE user_id = %s AND role = 'user' UNION ALL "
            "SELECT m.conversation_id, m.content, m.created_at, m.id FROM messages m "
            "JOIN conversations c ON c.id = m.conversation_id "
            "WHERE c.user_id = %s AND m.role = 'user'"
            ") AS user_messages ORDER BY created_at DESC, id DESC LIMIT %s",
            (user_id, user_id, limit),
        ).fetchall()


_RECALL_COMMON_WORDS = {
    "about", "again", "chat", "chats", "could", "from", "have", "information",
    "last", "please", "previous", "recall", "remember", "said", "saved", "should",
    "that", "their", "them", "this", "what", "when", "where", "which", "with", "would",
}


def search_user_text(user_id: str, query: str, conversation_id: str, limit: int = 4) -> list[dict]:
    """Recover clearly related past user statements without an embedding service."""
    def terms(text):
        return set(re.findall(r"\b[\w-]{4,}\b", text.casefold())) - _RECALL_COMMON_WORDS

    query_terms = terms(query)
    if not query_terms:
        return []
    matches = []
    seen = {query.strip().casefold()}
    for row in _recent_user_messages(user_id):
        if row["conversation_id"] == conversation_id:
            continue
        text = row["content"] or ""
        normalized = text.strip().casefold()
        if normalized in seen:
            continue
        overlap = query_terms & terms(text)
        if len(overlap) < 2 and not any(len(word) >= 8 for word in overlap):
            continue
        seen.add(normalized)
        matches.append((len(overlap), row["created_at"], row))
    matches.sort(key=lambda match: match[:2], reverse=True)
    return [row for _, _, row in matches[:limit]]


def latest_name(user_id: str, exclude_conversation_id: str | None = None) -> dict | None:
    """Return the newest explicit user-stated personal name.

    Same reasoning as latest_location: personal facts are too important to leave
    entirely to embedding rank. A live incident (2026-11-09, KoboldCPP
    Qwen3.8-2B): "what's my name?" ranked a stored past *refusal* ("I'm an AI
    assistant. I don't have a name...", 0.686) above the actual "My name is
    Maya Patel" chunk (0.568), and the soft recall framing let the model answer
    "You didn't tell me your name!" — while a directive-style fact fixed it.
    Non-personal phrasings ("my username is", "the file name is",
    "my name is not important") intentionally do not match these patterns.
    """
    for row in _recent_user_messages(user_id, limit=None):
        if row["conversation_id"] == exclude_conversation_id:
            continue
        text = (row["content"] or "").strip()
        for pattern in _NAME_PATTERNS:
            match = pattern.search(text)
            if match:
                value = re.split(r"\s+and\s+(?:i\b|my\b)", match.group(1), maxsplit=1,
                                 flags=re.I)[0].strip().rstrip(".!? ").strip("'\"")[:60]
                first_word = value.lower().split(None, 1)[0] if value else ""
                if value and first_word not in _NAME_REJECT_VALUES \
                        and not value.lower().startswith(("not ", "unknown")):
                    return {
                        "name": value,
                        "content": text,
                        "conversation_id": row["conversation_id"],
                        "created_at": row["created_at"],
                    }
    return None


def latest_location(user_id: str, exclude_conversation_id: str | None = None, *, state_only=False) -> dict | None:
    """Return the newest explicit user-stated home/current location.

    Personal facts are too important to leave entirely to embedding rank: generic
    weather refusals frequently score above an imperative such as "set my current
    location as Exampleville ZZ". Keep the source message so recall remains auditable.
    Store-specific addresses ("remember my Great Clips location") intentionally do
    not match these personal-location patterns.
    """
    patterns = (_STATE_PATTERN, *_LOCATION_PATTERNS) if state_only else _LOCATION_PATTERNS
    for row in _recent_user_messages(user_id, limit=None):
        if row["conversation_id"] == exclude_conversation_id:
            continue
        text = (row["content"] or "").strip()
        for pattern in patterns:
            match = pattern.search(text)
            if match:
                value = (requested_saved_location(text) if pattern is _REMEMBER_LOCATION
                         else match.group(1).strip().rstrip(".!? ")[:200])
                if not value:
                    continue
                # Ignore copied prompt placeholders such as
                # "[Clear, concise confirmation of your location]"; treating one
                # as a real saved place makes the recall directive reinforce it.
                if value.startswith("[") and value.endswith("]") and re.search(
                    r"\b(?:clear|concise|confirmation|placeholder|your location)\b", value, re.I
                ):
                    continue
                if value and not re.match(r"^(?:not\b|unknown\b|none\b)", value, re.I):
                    explicit = {
                        "location": value,
                        "is_state": pattern is _STATE_PATTERN,
                        "content": text,
                        "conversation_id": row["conversation_id"],
                        "created_at": row["created_at"],
                    }
                    return _location_from_followup(user_id, exclude_conversation_id, row["created_at"]) or explicit
    return _location_from_followup(user_id, exclude_conversation_id, 0)


def search(
    user_id: str,
    query_embedding: list[float],
    exclude_conversation_id: str | None = None,
    top_k: int = 8,
    min_similarity: float = 0.35,
    embedding_backend: str = "lemonade",
    *,
    role: str | None = None,
) -> list[dict]:
    """Search stored chunks by cosine similarity, scoped to the current user.

    Exclude the current conversation. A minimum similarity of 0.35 and a retrieval
    window of eight help retrieve short facts despite repeated similar questions."""
    with _connect() as conn:
        rows = conn.execute(
            "SELECT conversation_id, role, content, embedding, created_at FROM memory_chunks "
            "WHERE user_id = %s AND embedding_backend = %s",
            (user_id, embedding_backend),
        ).fetchall()

    candidates = [r for r in rows if r["conversation_id"] != exclude_conversation_id
                  and (role is None or r["role"] == role)]
    if not candidates:
        return []

    query = np.asarray(query_embedding, dtype=np.float32)
    query_norm = np.linalg.norm(query)
    if query_norm == 0:
        return []

    compatible = [
        (row, vector)
        for row in candidates
        if (vector := _decode_compatible_vector(row["embedding"], query.size)) is not None
    ]
    if not compatible:
        return []
    candidates = [row for row, _ in compatible]
    vectors = np.stack([vector for _, vector in compatible])
    norms = np.linalg.norm(vectors, axis=1)
    norms[norms == 0] = 1e-9
    similarities = (vectors @ query) / (norms * query_norm)

    ranked = sorted(zip(similarities, candidates),
                    key=lambda pair: (pair[0], pair[1]["created_at"]), reverse=True)
    results = []
    for similarity, row in ranked[:top_k]:
        if similarity < min_similarity:
            break
        results.append(
            {
                "conversation_id": row["conversation_id"],
                "role": row["role"],
                "content": row["content"],
                "created_at": row["created_at"],
                "similarity": float(similarity),
            }
        )
    return results
