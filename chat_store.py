"""PostgreSQL-backed persistence for chat conversations."""

from __future__ import annotations

import database
import time
import uuid

DATA_DIR = database.DATA_DIR

SCHEMA = """
CREATE TABLE IF NOT EXISTS conversations (
    id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    model TEXT,
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    user_id TEXT
);
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    role TEXT NOT NULL,
    content TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    duration DOUBLE PRECISION,
    model TEXT,
    backend TEXT,
    prompt_tokens INTEGER,
    completion_tokens INTEGER,
    total_tokens INTEGER,
    reasoning TEXT,
    npu_percent DOUBLE PRECISION,
    tops_used DOUBLE PRECISION,
    tops_max DOUBLE PRECISION
);
"""

_MESSAGE_MIGRATION_COLUMNS = [
    ("duration", "DOUBLE PRECISION"),
    ("model", "TEXT"),
    ("backend", "TEXT"),
    ("prompt_tokens", "INTEGER"),
    ("completion_tokens", "INTEGER"),
    ("total_tokens", "INTEGER"),
    ("reasoning", "TEXT"),
    ("npu_percent", "DOUBLE PRECISION"),
    ("tops_used", "DOUBLE PRECISION"),
    ("tops_max", "DOUBLE PRECISION"),
]

_CONVERSATION_MIGRATION_COLUMNS = [
    ("user_id", "TEXT"),
]


def _connect():
    return database.connect()


def init_db() -> None:
    with _connect() as conn:
        conn.execute(SCHEMA)
        for column, sql_type in _MESSAGE_MIGRATION_COLUMNS:
            conn.execute(f"ALTER TABLE messages ADD COLUMN IF NOT EXISTS {column} {sql_type}")
        for column, sql_type in _CONVERSATION_MIGRATION_COLUMNS:
            conn.execute(f"ALTER TABLE conversations ADD COLUMN IF NOT EXISTS {column} {sql_type}")


def assign_orphaned_conversations(user_id: str) -> int:
    """One-time migration helper: attach any pre-existing user_id-less conversations
    (from before multi-user support) to the given user. Returns the number updated."""
    with _connect() as conn:
        cur = conn.execute(
            "UPDATE conversations SET user_id = %s WHERE user_id IS NULL", (user_id,)
        )
        return cur.rowcount


def new_id() -> str:
    return uuid.uuid4().hex


def list_conversations(user_id: str) -> list[dict]:
    with _connect() as conn:
        rows = conn.execute(
            "SELECT id, title, model, created_at, updated_at FROM conversations "
            "WHERE user_id = %s ORDER BY updated_at DESC",
            (user_id,),
        ).fetchall()
        return [dict(r) for r in rows]


def get_conversation(conversation_id: str, user_id: str) -> dict | None:
    with _connect() as conn:
        conv = conn.execute(
            "SELECT id, title, model, created_at, updated_at FROM conversations "
            "WHERE id = %s AND user_id = %s",
            (conversation_id, user_id),
        ).fetchone()
        if conv is None:
            return None
        msgs = conn.execute(
            "SELECT role, content, created_at, duration, model, backend, "
            "prompt_tokens, completion_tokens, total_tokens, reasoning, "
            "npu_percent, tops_used, tops_max FROM messages "
            "WHERE conversation_id = %s ORDER BY id ASC",
            (conversation_id,),
        ).fetchall()
        result = dict(conv)
        result["messages"] = [dict(m) for m in msgs]
        return result


def delete_conversation(conversation_id: str, user_id: str) -> None:
    with _connect() as conn:
        conn.execute(
            "DELETE FROM conversations WHERE id = %s AND user_id = %s",
            (conversation_id, user_id),
        )


def delete_all_conversations_for_user(user_id: str) -> None:
    """Used when a user account is deleted, so their chats don't linger as orphaned rows."""
    with _connect() as conn:
        conn.execute("DELETE FROM conversations WHERE user_id = %s", (user_id,))


def truncate_messages(conversation_id: str, user_id: str, keep: int) -> bool:
    """Delete all but the first `keep` messages of a conversation (ordered by id, the
    same order get_conversation returns). Powers edit / regenerate / retry in the chat
    UI: those actions rewind the conversation to a point and re-run from there, and the
    stored history must be rewound to match before /api/chat appends the new turn —
    otherwise the earlier messages being replaced would linger as duplicates (the chat
    endpoint saves the user message as soon as it arrives, so a naive resend would
    double it). Ownership-scoped via the conversations join so one user can't truncate
    another's chat. Returns False if the conversation doesn't exist or isn't this
    user's. keep=0 clears every message (but keeps the conversation row)."""
    with _connect() as conn:
        owns = conn.execute(
            "SELECT 1 FROM conversations WHERE id = %s AND user_id = %s",
            (conversation_id, user_id),
        ).fetchone()
        if not owns:
            return False
        ids = [
            row[0]
            for row in conn.execute(
                "SELECT id FROM messages WHERE conversation_id = %s ORDER BY id ASC",
                (conversation_id,),
            ).fetchall()
        ]
        to_delete = ids[max(0, keep):]
        if to_delete:
            placeholders = ",".join(["%s"] * len(to_delete))
            conn.execute(
                f"DELETE FROM messages WHERE id IN ({placeholders})", to_delete
            )
        conn.execute(
            "UPDATE conversations SET updated_at = %s WHERE id = %s",
            (time.time(), conversation_id),
        )
        return True


def ensure_conversation(
    conversation_id: str, user_id: str, model: str | None, first_user_message: str | None
) -> None:
    now = time.time()
    with _connect() as conn:
        row = conn.execute(
            "SELECT id FROM conversations WHERE id = %s AND user_id = %s",
            (conversation_id, user_id),
        ).fetchone()
        if row is None:
            title = "New chat"
            if first_user_message:
                title = first_user_message.strip().splitlines()[0][:60] or title
            conn.execute(
                "INSERT INTO conversations (id, title, model, created_at, updated_at, user_id) "
                "VALUES (%s, %s, %s, %s, %s, %s)",
                (conversation_id, title, model, now, now, user_id),
            )
        else:
            conn.execute(
                "UPDATE conversations SET model = %s, updated_at = %s WHERE id = %s AND user_id = %s",
                (model, now, conversation_id, user_id),
            )


def add_message(
    conversation_id: str,
    role: str,
    content: str,
    duration: float | None = None,
    model: str | None = None,
    backend: str | None = None,
    prompt_tokens: int | None = None,
    completion_tokens: int | None = None,
    total_tokens: int | None = None,
    reasoning: str | None = None,
    npu_percent: float | None = None,
    tops_used: float | None = None,
    tops_max: float | None = None,
) -> None:
    now = time.time()
    with _connect() as conn:
        conn.execute(
            "INSERT INTO messages (conversation_id, role, content, created_at, duration, "
            "model, backend, prompt_tokens, completion_tokens, total_tokens, reasoning, "
            "npu_percent, tops_used, tops_max) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)",
            (
                conversation_id,
                role,
                content,
                now,
                duration,
                model,
                backend,
                prompt_tokens,
                completion_tokens,
                total_tokens,
                reasoning,
                npu_percent,
                tops_used,
                tops_max,
            ),
        )
        conn.execute(
            "UPDATE conversations SET updated_at = %s WHERE id = %s", (now, conversation_id)
        )
